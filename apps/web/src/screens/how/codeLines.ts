// build123d source shown in the Code tab (expert mode). Each line knows which part it builds,
// so selecting a part highlights its lines and clicking a line selects the part.
import { CFG } from '../../model/parts';
import type { Version } from '../../data/types';

export interface CodeLine { text: string; part: string | null; kind: '' | 'cm' | 'kw' }

export function codeLines(projectName: string, version: Version, head?: { branch: string; id: string }): CodeLine[] {
  const cf = CFG[version];
  const x0 = -110 + cf.t2;
  const L: CodeLine[] = [];
  const add = (text: string, part: string | null = null, kind: CodeLine['kind'] = '') => L.push({ text, part, kind });
  const slug = (projectName || 'mount').toLowerCase().replace(/[^a-z0-9]+/g, '_');

  add(`# ${projectName || 'Project'} · ${head ? `${head.branch} @ ${head.id}` : ''} · generated by Bot`, null, 'cm');
  add('from build123d import *', null, 'kw');
  add('');
  add('# Parameters (mm)', null, 'cm');
  add(`PLATE_T   = ${cf.t}      # base plate thickness`, 'plate');
  add(`UPRIGHT_T = ${cf.t2}      # upright thickness`, 'upright');
  if (cf.g) {
    add(`${cf.g === 'rib' ? 'RIB_T     = 5' : 'GUSSET_T  = 8'}       # ${cf.g === 'rib' ? 'rib' : 'gusset'} thickness`, 'gusset');
    add(`${cf.g === 'rib' ? 'RIB_H     = 62' : 'GUSSET_H  = 90'}      # leg length of the triangle`, 'gusset');
  }
  add('GEN_R, GEN_L = 46, 120 # bought-in generator', 'gen');
  add('AXIS_Z    = PLATE_T + 85', 'gen');
  add('');
  add('with BuildPart() as bracket:', null, 'kw');
  add('    # Base plate', 'plate', 'cm');
  add('    with Locations((0, 0, PLATE_T / 2)):', 'plate');
  add('        Box(220, 140, PLATE_T)', 'plate');
  add('    # Upright, welded to the plate', 'upright', 'cm');
  add('    with Locations((-110 + UPRIGHT_T / 2, 0, PLATE_T + 75)):', 'upright');
  add('        Box(UPRIGHT_T, 140, 150)', 'upright');
  if (cf.g) {
    const T = cf.g === 'rib' ? 'RIB_T' : 'GUSSET_T', H = cf.g === 'rib' ? 'RIB_H' : 'GUSSET_H', yy = cf.g === 'rib' ? 64 : 62;
    add(`    # ${cf.g === 'rib' ? 'Ribs' : 'Gussets'} at the upright root (2x)`, 'gusset', 'cm');
    add(`    for y in (-${yy}, ${yy}):`, 'gusset', 'kw');
    add(`        with BuildSketch(Plane.XZ.offset(-y - ${T} / 2)):`, 'gusset');
    add('            with Locations((-110 + UPRIGHT_T, PLATE_T)):', 'gusset');
    add(`                Polygon((0, 0), (${H}, 0), (0, ${H}), align=None)`, 'gusset');
    add(`        extrude(amount=${T})`, 'gusset');
  }
  add('    # Base bolt holes, 4x M10', 'bolts', 'cm');
  add('    with Locations(*[(x, y, PLATE_T) for x in (-85, 85) for y in (-55, 55)]):', 'bolts');
  add('        CounterBoreHole(radius=5.5, counter_bore_radius=9, counter_bore_depth=2)', 'bolts');
  add('    # Flange holes, 4x M8 on Ø104', 'flange', 'cm');
  add('    with BuildSketch(Plane.YZ.offset(-110)) as holes:', 'flange');
  add('        with PolarLocations(52, 4, start_angle=45):', 'flange');
  add('            Circle(4.5)', 'flange');
  add('    extrude(amount=UPRIGHT_T, mode=Mode.SUBTRACT)', 'flange');
  add('');
  add('# Bought-in parts (reference geometry)', null, 'cm');
  add(`flange = Cylinder(58, 8, rotation=(0, 90, 0)).locate(Location((${x0 + 4}, 0, AXIS_Z)))`, 'flange');
  add(`generator = Cylinder(GEN_R, GEN_L, rotation=(0, 90, 0)).locate(Location((${x0 + 68}, 0, AXIS_Z)))`, 'gen');
  add(`shaft = Cylinder(9, 60, rotation=(0, 90, 0)).locate(Location((${x0 + 158}, 0, AXIS_Z)))`, 'shaft');
  add(`hub = Cylinder(20, 20, rotation=(0, 90, 0)).locate(Location((${x0 + 198}, 0, AXIS_Z)))`, 'hub');
  add('bolts = [Cylinder(7, 6).locate(Location((x, y, PLATE_T + 3)))', 'bolts');
  add('         for x in (-85, 85) for y in (-55, 55)]', 'bolts');
  add('');
  add(`mount = Compound(label="${slug}",`);
  add('                 children=[bracket.part, flange, generator, shaft, hub, *bolts])');
  add(`export_step(mount, "${slug}_${head ? head.id : 'head'}.step")`);
  return L;
}
